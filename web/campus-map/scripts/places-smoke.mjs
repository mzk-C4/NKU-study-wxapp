import assert from 'node:assert/strict'
import {readFile} from 'node:fs/promises'
import {loadLocalTs} from './load-local-ts.mjs'
const {campusModel:model}=await loadLocalTs('src/data/campus-model.ts')
const {createPlaceCatalog}=await loadLocalTs('src/map-places.ts')
const {createPlaceSearch,normalizeSearch}=await loadLocalTs('src/map-search.ts')
const {layoutMapLabels}=await loadLocalTs('src/map-label-layout.ts')
const original=JSON.stringify(model),places=createPlaceCatalog(model),search=createPlaceSearch(places)
assert.equal(JSON.stringify(model),original,'Annotations must not mutate model data')
assert.equal(new Set(places.map(p=>p.id)).size,places.length)
for(const building of model.buildings){const p=places.find(p=>p.id===building.id);assert(p);assert.deepEqual(p.footprint,building.footprint);assert.equal(p.height,building.height)}
assert(places.filter(p=>p.labelVisible).length>70)
for(const p of places)assert(p.position.every(Number.isFinite)&&p.sourceNote)
for(const p of places.filter(p=>p.id.startsWith('place-')&&p.sourceNote.includes('估位')))assert(!p.buildingId,'Estimated reference labels must not create building geometry')
const first=(query,id)=>assert.equal(search(query)[0]?.id,id,query)
first('图书管','osm-building-616829077');first('图馆','osm-building-616829077')
first('tsg','osm-building-616829077');first('tushuguan','osm-building-616829077')
first('公教Ａ','osm-building-1430904058');first('公共教学 A','osm-building-1430904058')
first('公教D','osm-building-1436478222');first('综实b','osm-building-1456224123')
first('二食堂','osm-building-1412230608');first('学２食堂','osm-building-1412230608')
first('jsj','osm-building-1530053726');first('计院','osm-building-1530053726')
first('周恩莱雕像','reference-monument-zhou-enlai');first('5b宿舍','osm-building-1530053731')
first('理科 篮球','place-science-basketball');first('菜鸟','place-cainiao')
assert(!search('公教a').some(p=>p.id==='osm-building-1430904059'),'Do not fuzzy-swap wing letters')
assert.equal(normalizeSearch('学一食堂'),normalizeSearch('学1食堂'))
assert.equal(search('<script>pwned</script>').length,0);assert.equal(search('').length,0)
const candidates=[{id:'a',x:70,y:100,width:100,priority:10,selected:false},{id:'b',x:73,y:100,width:100,priority:10,selected:true},{id:'c',x:70,y:170,width:100,priority:10,selected:false}]
const layout=layoutMapLabels(candidates,300,400,[{left:0,top:0,right:300,bottom:60}])
assert(layout.has('b')&&layout.has('c')&&!layout.has('a'),'Selected labels win and overlapping labels are suppressed')
assert(!layoutMapLabels(candidates,300,400,[{left:0,top:0,right:300,bottom:400}]).size)
const main=await readFile('src/main.ts','utf8'),flat=await readFile('src/flat-map.ts','utf8')
assert(!main.includes('入口与服务点')&&!main.includes('campusModel.pois.forEach')&&!main.includes('poiGroup'))
assert(!flat.includes('model.pois.map'))
console.log(`Place catalog/search passed: ${places.length} entries, ${places.filter(p=>p.labelVisible).length} named labels; no model mutation, partial/alias/typo/ordered-token search, wing-number safety and label decluttering.`)
